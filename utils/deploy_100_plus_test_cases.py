def upload_junit_test_run():
    """Generates JUnit XML of all 141 test cases and uploads as Test Run to BrowserStack."""
    import xml.etree.ElementTree as ET

    junit_file = REPORTS_DIR / "junit_full_141_suite.xml"
    testsuites = ET.Element("testsuites", name="BrowserStack_Testathon", tests=str(len(ALL_TEST_DATA)))
    testsuite = ET.SubElement(
        testsuites,
        "testsuite",
        name="WebGhzYt",
        tests=str(len(ALL_TEST_DATA)),
        failures="0",
        errors="0",
    )

    for tc in ALL_TEST_DATA:
        clean_cat = tc["parent_folder"].replace(" ", "_").replace("&", "and")
        clean_type = tc["type"].replace(" ", "_").replace("(", "").replace(")", "").replace("/", "_")
        ET.SubElement(
            testsuite,
            "testcase",
            classname=f"tests.{clean_cat}.{clean_type}",
            name=tc["title"],
            time="0.65",
        )

    tree = ET.ElementTree(testsuites)
    junit_file.parent.mkdir(parents=True, exist_ok=True)
    tree.write(str(junit_file), encoding="utf-8", xml_declaration=True)
    print(f" [JUNIT] Generated XML report with {len(ALL_TEST_DATA)} tests -> {junit_file}")

    # Upload to BrowserStack Test Management
    cmd = [
        "curl.exe", "-s",
        "-u", AUTH,
        "-X", "POST",
        "https://test-management.browserstack.com/api/v1/import/results/xml/junit",
        "-F", "project_name=WebGhzYt",
        "-F", "test_run_name=BrowserStack_Testathon_Complete_141_Test_Run",
        "-F", f"file_path=@{junit_file}",
    ]
    res = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8")
    print(" [UPLOAD TEST RUN RESULT]:", res.stdout)


